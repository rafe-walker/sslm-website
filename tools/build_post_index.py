#!/usr/bin/env python3
"""
build_post_index.py — regenerate app/blog/posts/index.ts from the post files.

Every blog post lives in its own file under app/blog/posts/. Next needs static
imports, so the index cannot glob the directory at runtime; this script writes
the import list instead. Run it after adding or removing a post:

    python3 tools/build_post_index.py

The alternative — hand-editing a 20-import file every time — is exactly the kind
of step that gets skipped, and a post missing from the index is a post missing
from the sitemap, the blog page and the related-posts links, with no error.
"""

import os
import re
import sys

POSTS = "app/blog/posts"
INDEX = os.path.join(POSTS, "index.ts")

HEADER = '''// AUTO-GENERATED by tools/build_post_index.py — do not edit by hand.
// Add a post file to app/blog/posts/ and re-run the script.

import type { BlogPost } from '../types'
'''

FOOTER = '''
/**
 * Display order for the blog index. A category that appears on a post but not
 * in this list is silently dropped from the index page, so keep them in step.
 */
export const CATEGORY_ORDER = [
  'Rural Living',
  'Land Clearing',
  'Land Preparation',
  'Off-Grid Living',
  'Industry',
  'Local Businesses',
] as const

export function postBySlug(slug: string): BlogPost | undefined {
  return blogPosts.find((p) => p.slug === slug)
}

/**
 * Related posts: same category first, then the rest by recency. Prefers posts
 * the current one links to conceptually over pure chronology, because an
 * article about caliche is more useful next to the septic article than next to
 * whatever happened to publish the same week.
 */
export function relatedTo(post: BlogPost, limit = 4): BlogPost[] {
  const others = blogPosts.filter((p) => p.id !== post.id)
  const scored = others
    .map((p) => ({
      p,
      score:
        (p.category === post.category ? 2 : 0) +
        (p.keywords.some((k) => post.keywords.includes(k)) ? 1 : 0),
    }))
    .sort((a, b) => b.score - a.score || (a.p.date < b.p.date ? 1 : -1))
  return scored.slice(0, limit).map((s) => s.p)
}
'''


def main():
    if not os.path.isdir(POSTS):
        sys.exit(f"{POSTS} not found — run from the repo root.")

    files = sorted(
        f[:-3] for f in os.listdir(POSTS)
        if f.endswith(".ts") and f != "index.ts"
    )
    if not files:
        sys.exit("No post files found.")

    entries = []
    for slug in files:
        text = open(os.path.join(POSTS, f"{slug}.ts"), encoding="utf-8").read()
        m = re.search(r"export const (\w+): BlogPost", text)
        if not m:
            sys.exit(f"{slug}.ts has no `export const <name>: BlogPost`")
        date = re.search(r"date:\s*['\"](\d{4}-\d{2}-\d{2})['\"]", text)
        if not date:
            sys.exit(f"{slug}.ts has no date")
        entries.append((date.group(1), m.group(1), slug))

    # Newest first in the array so anything that forgets to sort still gets a
    # sensible order.
    entries.sort(reverse=True)

    lines = [HEADER]
    for _, var, slug in entries:
        lines.append(f"import {{ {var} }} from './{slug}'")
    lines.append("\nexport type { BlogPost } from '../types'\n")
    lines.append("export const blogPosts: BlogPost[] = [")
    for _, var, _slug in entries:
        lines.append(f"  {var},")
    lines.append("]")
    lines.append(FOOTER)

    open(INDEX, "w", encoding="utf-8").write("\n".join(lines))
    print(f"Wrote {INDEX} with {len(entries)} posts "
          f"({entries[-1][0]} .. {entries[0][0]})")


if __name__ == "__main__":
    main()
